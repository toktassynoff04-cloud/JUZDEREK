(()=>{
  const patchChapterMap=()=>{
    const groups=window.JUZDEREK_CHAPTER_MAP?.medieval||[];
    const mongols=groups.find(c=>c?.[0]==='mongols');
    if(mongols&&Array.isArray(mongols[2])){
      const replacements={
        'Моңғол империясының құрылуы':'Алтын Орда',
        'Моңғолдардың әскери өнері':'Юань империясы',
        'Моңғол шапқыншылығының Еуразия картасына әсері':'Хулагу мемлекеті'
      };
      mongols[2]=mongols[2].map(name=>replacements[name]||name).filter(name=>name!=='Құбылай мемлекеті, Ильханат');
      if(!mongols[2].includes('Шағатай мемлекеті')) mongols[2].push('Шағатай мемлекеті');
    }
    const europe=groups.find(c=>c?.[0]==='europe');
    if(europe&&Array.isArray(europe[2])){
      const merged="Феодалдық соғыстар. Жанна д'Арк";
      const next=[];
      for(const name of europe[2]){
        if(name==='Феодалдық соғыстар'){
          if(!next.includes(merged)) next.push(merged);
          continue;
        }
        if(name==='Жанна д’Арк'||name==="Жанна д'Арк"||name==='Еуропадағы орталықтанған мемлекеттердің қалыптасуы') continue;
        next.push(name);
      }
      europe[2]=next;
    }
    const absolutism=groups.find(c=>c?.[0]==='absolutism');
    if(absolutism&&Array.isArray(absolutism[2])){
      const next=[];
      for(const name of absolutism[2]){
        if(name==='Феодалдық мемлекеттің даму кезеңдері'){ next.push('Феодалдық мемлекеттердің даму кезеңдері'); continue; }
        if(name==='Англия мен Ресейдегі абсолютизм'){ next.push('Англиядағы абсолютизм','Ресейдегі абсолютизм'); continue; }
        if(name==='Қытай мен Жапонияның саяси жүйесіндегі ерекшеліктер'){ next.push('Қытай саяси жүйесіндегі ерекшеліктер','Жапониядағы абсолютизм'); continue; }
        next.push(name);
      }
      const centralized='Еуропадағы орталықтанған мемлекеттердің қалыптасуы';
      if(!next.includes(centralized)) next.unshift(centralized);
      absolutism[2]=next;
    }
    if(typeof renderTopics==='function')renderTopics();
    if(typeof syncHero==='function')syncHero();
  };
  const existing=document.querySelector('script[data-juz-chapters]');
  if(existing){
    if(window.JUZDEREK_CHAPTER_MAP)patchChapterMap();
    else existing.addEventListener('load',patchChapterMap,{once:true});
    return;
  }
  const s=document.createElement('script');
  s.src='./chapter-navigation.js?v=20260820-chapters-v1';
  s.dataset.juzChapters='1';
  s.addEventListener('load',patchChapterMap,{once:true});
  document.head.appendChild(s);
})();
